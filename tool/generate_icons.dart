// Generates the app icons, one per accent color, from the shield in
// assets/icon.png (only its alpha channel is used):
//
//   dart run tool/generate_icons.dart [--preview <dir>]
//
// Android: an adaptive icon per accent (light shield on a dark tile of the
// same hue), a legacy icon for Android 7, and a shared monochrome layer for
// themed icons. Each accent has an activity alias in AndroidManifest.xml.
// Windows: one .ico per accent, embedded in the exe (see Runner.rc).
//
// The colors come from the same vibrant Material 3 scheme as the app theme
// (lib/theme/app_theme.dart), so the icon matches the accent inside the app.
import 'dart:io';

import 'package:file_vault/theme/app_accent.dart';
import 'package:image/image.dart' as img;
import 'package:material_color_utilities/material_color_utilities.dart';

const _source = 'assets/icon.png';
const _androidRes = 'android/app/src/main/res';
const _windowsRes = 'windows/runner/resources';

/// Supersampling canvas; everything is drawn here, then averaged down.
const _canvas = 1024;

const _densities = {
  'mdpi': 1.0,
  'hdpi': 1.5,
  'xhdpi': 2.0,
  'xxhdpi': 3.0,
  'xxxhdpi': 4.0,
};

/// Shield size as a fraction of the adaptive icon's 108dp canvas. Launchers
/// only guarantee the central 66dp circle is visible.
const _adaptiveShield = 0.56;

/// Shield size and corner radius on the tile used where there is no adaptive
/// mask (Windows, Android 7 and older).
const _tileShield = 0.64;
const _tileRadius = 0.225;
const _tileMargin = 0.0625;

class IconColors {
  final int shield;
  final int background;
  const IconColors(this.shield, this.background);

  /// Light (dark-theme primary, tone 80) shield on a deep tone of the same
  /// hue: the shield stays vivid, and the tile stands out on both light and
  /// dark wallpapers and taskbars.
  factory IconColors.of(AppAccent accent) {
    final scheme = SchemeVibrant(
      sourceColorHct: Hct.fromInt(accent.seedArgb),
      isDark: true,
      contrastLevel: 0,
    );
    return IconColors(
      MaterialDynamicColors.primary.getArgb(scheme),
      scheme.primaryPalette.get(_backgroundTone),
    );
  }
}

const _backgroundTone = 20;

void main(List<String> args) {
  final previewIndex = args.indexOf('--preview');
  final previewDir = previewIndex >= 0 ? args[previewIndex + 1] : null;

  final source = img.decodePng(File(_source).readAsBytesSync())!;
  final mask = _alphaMask(source);

  if (previewDir != null) {
    _writePreview(mask, previewDir);
    return;
  }

  _cleanOldAndroidIcons();
  final colorsXml = StringBuffer()
    ..writeln('<?xml version="1.0" encoding="utf-8"?>')
    ..writeln('<!-- Generated by tool/generate_icons.dart. -->')
    ..writeln('<resources>');

  for (final accent in AppAccent.values) {
    final colors = IconColors.of(accent);
    final id = accent.id;
    colorsXml.writeln(
      '    <color name="ic_launcher_background_$id">'
      '${_hex(colors.background)}</color>',
    );

    final foreground = _adaptiveLayer(mask, colors.shield);
    final tile = _tile(mask, colors);
    for (final MapEntry(key: density, value: scale) in _densities.entries) {
      _writePng(
        '$_androidRes/drawable-$density/ic_launcher_foreground_$id.png',
        _downscale(foreground, (108 * scale).round()),
      );
      _writePng(
        '$_androidRes/mipmap-$density/ic_launcher_$id.png',
        _downscale(tile, (48 * scale).round()),
      );
    }
    _writeText(
      '$_androidRes/mipmap-anydpi-v26/ic_launcher_$id.xml',
      _adaptiveXml(id),
    );

    final ico = img.IcoEncoder().encodeImages([
      for (final size in const [16, 20, 24, 32, 40, 48, 64, 128, 256])
        _downscale(tile, size),
    ]);
    File('$_windowsRes/app_icon_$id.ico').writeAsBytesSync(ico);
  }

  // Android 13+ themed icons tint this layer; it is the same for all accents.
  final monochrome = _adaptiveLayer(mask, 0xFFFFFFFF);
  for (final MapEntry(key: density, value: scale) in _densities.entries) {
    _writePng(
      '$_androidRes/drawable-$density/ic_launcher_monochrome.png',
      _downscale(monochrome, (108 * scale).round()),
    );
  }

  colorsXml.writeln('</resources>');
  _writeText(
    '$_androidRes/values/ic_launcher_colors.xml',
    colorsXml.toString(),
  );
  stdout.writeln('Generated icons for ${AppAccent.values.length} accents.');
}

/// The shield's alpha, centered on a square [_canvas].
img.Image _alphaMask(img.Image source) {
  final resized = img.copyResize(
    source,
    width: _canvas,
    height: _canvas,
    interpolation: img.Interpolation.cubic,
  );
  return resized.convert(numChannels: 4);
}

/// [mask] in [color], scaled to [fraction] of a transparent [_canvas].
img.Image _shield(img.Image mask, int color, double fraction) {
  final size = (_canvas * fraction).round();
  final scaled = img.copyResize(
    mask,
    width: size,
    height: size,
    interpolation: img.Interpolation.average,
  );
  final out = img.Image(width: _canvas, height: _canvas, numChannels: 4);
  final offset = (_canvas - size) ~/ 2;
  final r = (color >> 16) & 0xFF, g = (color >> 8) & 0xFF, b = color & 0xFF;
  for (final p in scaled) {
    final a = p.a.toInt();
    if (a == 0) continue;
    out.setPixelRgba(p.x + offset, p.y + offset, r, g, b, a);
  }
  return out;
}

img.Image _adaptiveLayer(img.Image mask, int color) =>
    _shield(mask, color, _adaptiveShield);

img.Image _tile(img.Image mask, IconColors colors) {
  final out = img.Image(width: _canvas, height: _canvas, numChannels: 4);
  final margin = (_canvas * _tileMargin).round();
  img.fillRect(
    out,
    x1: margin,
    y1: margin,
    x2: _canvas - margin - 1,
    y2: _canvas - margin - 1,
    radius: _canvas * _tileRadius,
    color: _color(colors.background),
  );
  return img.compositeImage(out, _shield(mask, colors.shield, _tileShield));
}

img.Image _downscale(img.Image src, int size) => img.copyResize(
  src,
  width: size,
  height: size,
  interpolation: img.Interpolation.average,
);

img.Color _color(int argb) => img.ColorRgba8(
  (argb >> 16) & 0xFF,
  (argb >> 8) & 0xFF,
  argb & 0xFF,
  (argb >> 24) & 0xFF,
);

String _hex(int argb) =>
    '#${(argb & 0xFFFFFF).toRadixString(16).padLeft(6, '0').toUpperCase()}';

String _adaptiveXml(String id) =>
    '''
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_icons.dart. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
  <background android:drawable="@color/ic_launcher_background_$id"/>
  <foreground android:drawable="@drawable/ic_launcher_foreground_$id"/>
  <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
''';

/// Removes the single-icon files flutter_launcher_icons used to generate.
void _cleanOldAndroidIcons() {
  final old = [
    '$_androidRes/mipmap-anydpi-v26/ic_launcher.xml',
    '$_androidRes/values/colors.xml',
    for (final d in _densities.keys) ...[
      '$_androidRes/mipmap-$d/ic_launcher.png',
      '$_androidRes/drawable-$d/ic_launcher_foreground.png',
    ],
    '$_windowsRes/app_icon.ico',
  ];
  for (final path in old) {
    final f = File(path);
    if (f.existsSync()) f.deleteSync();
  }
}

/// One sheet per accent: the adaptive icon under a circle and a squircle
/// mask, and the tile, on a light and a dark background.
void _writePreview(img.Image mask, String dir) {
  const cell = 160, pad = 16;
  final accents = AppAccent.values;
  final sheet = img.Image(
    width: pad + accents.length * (cell + pad),
    height: pad + 6 * (cell + pad),
    numChannels: 4,
  );
  img.fill(sheet, color: img.ColorRgba8(128, 128, 128, 255));
  for (final (i, accent) in accents.indexed) {
    final colors = IconColors.of(accent);
    final x = pad + i * (cell + pad);
    for (final (row, dark) in [(0, false), (3, true)]) {
      final bg = dark ? 0xFF000000 : 0xFFFFFFFF;
      final y0 = pad + row * (cell + pad);
      img.fillRect(
        sheet,
        x1: x - pad ~/ 2,
        y1: y0 - pad ~/ 2,
        x2: x + cell + pad ~/ 2,
        y2: y0 + 3 * (cell + pad) - pad ~/ 2,
        color: _color(bg),
      );
      final adaptive = img.Image(
        width: _canvas,
        height: _canvas,
        numChannels: 4,
      );
      img.fillCircle(
        adaptive,
        x: _canvas ~/ 2,
        y: _canvas ~/ 2,
        radius: (_canvas * 66 / 108 / 2 * 1.1).round(),
        color: _color(colors.background),
        antialias: true,
      );
      img.compositeImage(adaptive, _adaptiveLayer(mask, colors.shield));
      img.compositeImage(sheet, _downscale(adaptive, cell), dstX: x, dstY: y0);
      img.compositeImage(
        sheet,
        _downscale(_tile(mask, colors), cell),
        dstX: x,
        dstY: y0 + cell + pad,
      );
      img.compositeImage(
        sheet,
        _downscale(_tile(mask, colors), 32),
        dstX: x + (cell - 32) ~/ 2,
        dstY: y0 + 2 * (cell + pad) + (cell - 32) ~/ 2,
      );
    }
  }
  Directory(dir).createSync(recursive: true);
  _writePng('$dir/icons_preview.png', sheet);
  stdout.writeln('Wrote $dir/icons_preview.png');
}

void _writePng(String path, img.Image image) {
  File(path)
    ..parent.createSync(recursive: true)
    ..writeAsBytesSync(img.encodePng(image));
}

void _writeText(String path, String text) {
  File(path)
    ..parent.createSync(recursive: true)
    ..writeAsStringSync(text);
}
